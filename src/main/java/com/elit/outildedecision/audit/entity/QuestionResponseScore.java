package com.elit.outildedecision.audit.entity;

import com.fasterxml.jackson.annotation.JsonBackReference;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.GenerationType;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.FetchType;
import jakarta.persistence.Column;
import java.io.Serializable;

@Entity
@Table(name = "question_response_score")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class QuestionResponseScore implements Serializable {

  /**
   * Unique identifier for the question response score.
   * Automatically generated by the database.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /**
   * The audit score to which this question response belongs.
   * Represents the parent audit scoring context.
   */

  @ManyToOne(optional = false, fetch = FetchType.LAZY)
  @JoinColumn(name = "audit_score_id", referencedColumnName = "id")
  @JsonBackReference("auditScore_questionResponses")
  private AuditScore auditScore;

  /**
   * The question associated with this response.
   * Links the response to the specific audit question.
   */
  @ManyToOne(optional = false, fetch = FetchType.LAZY)
  @JoinColumn(name = "question_id", referencedColumnName = "questionId")
  private Question question;

  /**
   * The label of the answer provided for this question.
   * Useful for displaying the selected answer in reports or UI.
   */
  @Column(name = "answer_label", nullable = false)
  private String answerLabel;

  /**
   * The value of the answer provided for this question.
   * Typically used for scoring calculations.
   */
  @Column(name = "answer_value", nullable = false)
  private Integer answerValue;

  /**
   * The calculated score for this question response.
   * Represents the effective score based on the answer and question weight.
   */
  @Column(name = "score", nullable = false)
  private Double score;
}
