package com.elit.outildedecision.audit.entity;

import com.elit.outildedecision.audit.entity.comment.GlobalComment;
import com.elit.outildedecision.entity.User;
import com.fasterxml.jackson.annotation.JsonBackReference;
import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonManagedReference;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Column;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.CascadeType;
import jakarta.persistence.GenerationType;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import java.io.Serializable;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

@Entity
@Table(name = "audit_score")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class AuditScore implements Serializable {


/**
 * Unique identifier for the audit score.
 * Automatically generated by the database.
 */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /**
   * The audit associated with this score.
   * This is a one-to-one relationship and must not be null.
   * Ensures that each audit has a single corresponding score.
   */
  @OneToOne(optional = false)
  @JoinColumn(name = "audit_id", referencedColumnName = "auditId", unique = true)
  @NotNull(message = "L'audit est obligatoire")
  @JsonBackReference("audit_auditScore")
  private Audit audit;

  /**
   * The user who submitted or calculated the audit score.
   * This is a many-to-one relationship and must not be null.
   */
  @ManyToOne(optional = false)
  @JoinColumn(name = "user_id", referencedColumnName = "userId")
  @NotNull(message = "Le User est obligatoire")
  private User user;


  /**
   * The global score percentage calculated for the audit.
   * Must be between 0 and 100.
   */
  @NotNull
  @Min(0)
  @Max(100)
  @Column(name = "global_score_percentage", nullable = false)
  private Double globalScorePercentage;

  /**
   * Référence au template global utilisé (FK informative).
   */
  @ManyToOne(fetch = FetchType.LAZY)
  @JoinColumn(name = "global_comment_id")
  private GlobalComment globalComment;

  /**
   * List of the scores by audit category.
   */
  @Builder.Default
  @OneToMany(mappedBy = "auditScore", cascade = CascadeType.ALL, orphanRemoval = true)
  @JsonManagedReference("auditScore_categoryResults")
  private List<AuditCategoryResult> auditCategoryResults = new ArrayList<>();

  /**
   * List of individual question response scores associated with this audit score.
   * Each entry represents the score for a specific question answered during the audit.
   */
  @Builder.Default
  @OneToMany(mappedBy = "auditScore", cascade = CascadeType.ALL, orphanRemoval = true)
  @JsonManagedReference("auditScore_questionResponses")
  private List<QuestionResponseScore> questionResponses = new ArrayList<>();

  /**
   * The date and time when the audit score was submitted or calculated.
   * Automatically formatted for JSON serialization.
   */
  @Column(name = "submission_date", nullable = false)
  @JsonFormat(pattern = "dd-MM-yyyy HH:mm:ss", timezone = "Europe/Paris")
  private Timestamp submissionDate;
}
