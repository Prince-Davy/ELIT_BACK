package com.elit.outildedecision.audit.entity;


import com.elit.outildedecision.util.MethodType;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.SuperBuilder;

import javax.persistence.GeneratedValue;
import javax.persistence.Id;
import javax.persistence.MappedSuperclass;
import javax.persistence.GenerationType;
import javax.persistence.Column;
import javax.persistence.Enumerated;
import javax.persistence.EnumType;


@MappedSuperclass
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@SuperBuilder
public abstract class AbstractComment {

  /**
   * Unique identifier for the category comment.
   * Automatically generated by the database.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /**
   * Methodology used for the audit.
   * Allows extending functionality without modifying core audit logic.
   */
  @Column(name = "method_type", insertable = false, updatable = false)
  @Enumerated(EnumType.STRING)
  private MethodType method;


  /**
   * The evaluation level (e.g., BON, MOYEN, MAUVAIS) this comment corresponds to.
   * Stored as a string in the database.
   */
  @Enumerated(EnumType.STRING)
  @Column(name = "level", nullable = false)
  private LevelScore level;

  /**
   * The textual content of the comment.
   * Provides qualitative feedback based on the category and level.
   */
  @Column(name = "text", nullable = false, length = 1000)
  private String text;
}

