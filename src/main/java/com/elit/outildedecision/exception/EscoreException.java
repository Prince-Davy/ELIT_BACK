package com.elit.outildedecision.exception;

public class EscoreException extends Exception {

    public EscoreException() {
        super();
    }

    public EscoreException(String message) {
        super(message);
    }

    public EscoreException(String message, Throwable cause) {
        super(message, cause);
    }

    public EscoreException(Throwable cause) {
        super(cause);
    }
}
